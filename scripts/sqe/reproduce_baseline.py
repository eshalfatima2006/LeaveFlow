ROOT = Path(__file__).resolve().parents[2]
BACKEND = ROOT / "backend"
DEV_DB = BACKEND / "db.sqlite3"
SETTINGS_MODULE = "baseline_repro_settings"


def utc():
    return datetime.now(timezone.utc).isoformat(timespec="seconds")


def dev_db_metadata():
    """Metadata only: the development database file is never opened."""
    result = {}
    for suffix in ("", "-wal", "-shm", "-journal"):
        path = BACKEND / f"db.sqlite3{suffix}"
        if path.exists():
            stat = path.stat()
            result[path.name] = {"exists": True, "size": stat.st_size, "mtime_ns": stat.st_mtime_ns, "inode": stat.st_ino}
        else:
            result[path.name] = {"exists": False}
    return result


class Recorder:
    def __init__(self, evidence, run_dir):
        self.evidence, self.run_dir = evidence, run_dir
        self.steps = []

    def env(self):
        env = {k: v for k, v in os.environ.items() if not k.startswith("POSTGRES_") and k != "REDIS_URL"}
        env["DJANGO_SETTINGS_MODULE"] = SETTINGS_MODULE
        env["PYTHONPATH"] = os.pathsep.join([str(self.run_dir), str(BACKEND)])
        env["PYTHONDONTWRITEBYTECODE"] = "1"
        return env

    def run(self, name, command, cwd=BACKEND, extra_env=None, note=""):
        env = self.env()
        env.update(extra_env or {})
        started = utc()
        completed = subprocess.run(command, cwd=cwd, env=env, capture_output=True, text=True)
        finished = utc()
        output = completed.stdout + completed.stderr
        # shlex.join quotes multi-line `-c` code; strip line ends so headers carry no trailing whitespace.
        command_text = "\n".join(line.rstrip() for line in shlex.join(command).splitlines())
        header = [
            f"Command: {command_text}",
            f"Working directory: {Path(cwd).relative_to(ROOT) if Path(cwd).is_relative_to(ROOT) else cwd}",
            f"Django settings: {SETTINGS_MODULE} (disposable SQLite inside {self.run_dir})",
            f"Started (UTC): {started}",
            f"Finished (UTC): {finished}",
            f"Exit code: {completed.returncode}",
        ]
        if note:
            header.append(f"Note: {note}")
        (self.evidence / f"{name}.log").write_text("\n".join(header) + "\n----- output (stdout+stderr, unedited) -----\n" + output)
        self.steps.append({"step": name, "command": shlex.join(command), "exit_code": completed.returncode})
        return completed.returncode, output


def write_settings(run_dir):
    database = run_dir / "baseline-repro.sqlite3"
    (run_dir / f"{SETTINGS_MODULE}.py").write_text(
        "# Generated by scripts/sqe/reproduce_baseline.py: disposable database only.\n"
        "from config.settings import *  # noqa: F401,F403\n"
        f"DATABASES = {{'default': {{'ENGINE': 'django.db.backends.sqlite3', 'NAME': {str(database)!r}}}}}\n"
        "REDIS_URL = ''\n"
        "ALLOWED_HOSTS = ['127.0.0.1', 'localhost']\n"
    )
    return database


def capture(command):
    try:
        out = subprocess.run(command, capture_output=True, text=True, timeout=30)
        return (out.stdout or out.stderr).strip()
    except (OSError, subprocess.TimeoutExpired) as exc:
        return f"unavailable: {exc}"


def environment(evidence):
    packages = {}
    for name in ("Django", "djangorestframework", "django-cors-headers", "redis", "psycopg", "gunicorn", "pip"):
        try:
            packages[name] = metadata.version(name)
        except metadata.PackageNotFoundError:
            packages[name] = "not installed"
    git = lambda *a: capture(["git", "-C", str(ROOT), *a])
    data = {
        "recorded_at_utc": utc(),
        "uname": capture(["uname", "-a"]),
        "os_release": capture(["cat", "/etc/os-release"]),
        "kernel_release": capture(["cat", "/proc/sys/kernel/osrelease"]),
        "python": sys.version,
        "python_executable": sys.executable,
        "packages": packages,
        "node": capture(["node", "--version"]),
        "npm": capture(["npm", "--version"]),
        "git": capture(["git", "--version"]),
        "git_head": git("rev-parse", "HEAD"),
        "git_branch": git("branch", "--show-current"),
        "git_status_short": git("status", "--short").splitlines(),
        "database_engine_for_reproduction": "SQLite (disposable file in a new temporary directory)",
        "redis": "disabled (REDIS_URL empty)",
    }
    (evidence / "01-environment.json").write_text(json.dumps(data, indent=2) + "\n")
    return data


def port_free(port):
    with socket.socket() as sock:
        return sock.connect_ex(("127.0.0.1", port)) != 0


def http(base, method, path, body=None, token=None):
    request = urllib.request.Request(base + path, method=method, data=json.dumps(body).encode() if body is not None else None)
    request.add_header("Content-Type", "application/json")
    if token:
        request.add_header("Authorization", f"Token {token}")
    try:
        with urllib.request.urlopen(request, timeout=15) as response:
            return response.status, json.loads(response.read() or b"null")
    except urllib.error.HTTPError as error:
        raw = error.read()
        try:
            return error.code, json.loads(raw or b"null")
        except json.JSONDecodeError:
            return error.code, {"non_json_body_bytes": len(raw)}


def shell_json(recorder, name, code, extra_env):
    exit_code, output = recorder.run(name, [sys.executable, "manage.py", "shell", "-c", code], extra_env=extra_env)
    lines = [line for line in output.splitlines() if line.strip().startswith("{")]
    if exit_code != 0 or not lines:
        raise RuntimeError(f"{name} failed (exit {exit_code})")
    return json.loads(lines[-1])


