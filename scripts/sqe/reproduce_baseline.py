#!/usr/bin/env python3
"""Reproduce the PR #1 baseline checks against a disposable SQLite database.

Usage (repository root, inside WSL, with the project virtual environment):

    .venv/bin/python scripts/sqe/reproduce_baseline.py \
        --evidence-dir docs/sqe/evidence/baseline/reproduction-<date>

What it does, in order (every command's real output and exit code is saved):
  01 environment capture (OS/WSL kernel, Python, packages, Node/npm, Git state)
  02 settings guard: proves Django resolves to the disposable database only
  03 manage.py check
  04 manage.py showmigrations (before)    05 manage.py migrate
  06 manage.py showmigrations (after)     07 manage.py migrate --check
  08 manage.py test leave -v 2            (upstream tests only)
  09 HTTP API smoke test on a live runserver with synthetic users + DB readback
  10 npm run build in a temporary copy of frontend/ (optional)

Safety: Django runs with a generated settings module whose only database is a
SQLite file inside a new temporary directory; Redis is disabled; PostgreSQL
variables are removed. The development database (backend/db.sqlite3) is never
opened: only its file metadata is compared before and after. No seed, flush or
reset command is run anywhere. Generated passwords and API tokens are never
written to evidence. The evidence directory must not exist yet.
"""

import argparse
from datetime import datetime, timezone
from importlib import metadata
