def api_smoke(recorder, evidence, port):
    if not port_free(port):
        raise RuntimeError(f"Port {port} is already in use; refusing to talk to an unknown server.")
    passwords = {"SMOKE_EMPLOYEE_PASSWORD": secrets.token_urlsafe(16), "SMOKE_MANAGER_PASSWORD": secrets.token_urlsafe(16)}
    fixture = shell_json(recorder, "09a-api-fixture", FIXTURE_CODE, passwords)
    base = f"http://127.0.0.1:{port}"
    log = open(evidence / "09b-api-server.log", "w")
    log.write(f"Command: {sys.executable} manage.py runserver 127.0.0.1:{port} --noreload\n"
              f"Django settings: {SETTINGS_MODULE} (disposable SQLite inside {recorder.run_dir})\n----- server output -----\n")
    log.flush()
    server = subprocess.Popen([sys.executable, "manage.py", "runserver", f"127.0.0.1:{port}", "--noreload"],
                              cwd=BACKEND, env=recorder.env(), stdout=log, stderr=subprocess.STDOUT)
    checks = []

    def check(step, description, method, path, expected, body=None, token=None, fields=None):
        status, payload = http(base, method, path, body, token)
        entry = {"step": step, "description": description, "request": f"{method} {path}",
                 "authenticated_as": token and ("employee" if token == tokens.get("employee") else "manager"),
                 "expected_status": expected, "actual_status": status}
        if fields:
            entry["response_fields"] = fields(payload)
        entry["pass"] = status == expected and all(v is not False for v in entry.get("response_fields", {}).values() if isinstance(v, bool))
        checks.append(entry)
        return status, payload

    tokens = {}
    try:
        for _ in range(60):
            try:
                if http(base, "GET", "/health/")[0] == 200:
                    break
            except OSError:
                pass
            time.sleep(0.5)
        else:
            raise RuntimeError("runserver did not become healthy")
        check("S01", "Unauthenticated current-user lookup is refused", "GET", "/api/me/", 401,
              fields=lambda p: {"detail_present": bool(p and p.get("detail"))})
        check("S02", "Login with a wrong password is refused", "POST", "/api/auth/login/", 400,
              body={"username": "smoke-employee", "password": "wrong-password"}, fields=lambda p: {"detail": p.get("detail")})
        for role, key in (("employee", "SMOKE_EMPLOYEE_PASSWORD"), ("manager", "SMOKE_MANAGER_PASSWORD")):
            status, payload = http(base, "POST", "/api/auth/login/", {"username": f"smoke-{role}", "password": passwords[key]})
            tokens[role] = payload.get("token") if status == 200 else None
            checks.append({"step": "S03" if role == "employee" else "S04", "description": f"Synthetic {role} logs in",
                           "request": "POST /api/auth/login/", "expected_status": 200, "actual_status": status,
                           "response_fields": {"user.username": payload.get("user", {}).get("username"),
                                               "user.role": payload.get("user", {}).get("role"),
                                               "token": "<redacted>" if tokens[role] else None,
                                               "token_is_40_hex": bool(tokens[role] and re.fullmatch(r"[0-9a-f]{40}", tokens[role]))},
                           "pass": status == 200 and bool(tokens[role])})
        if not all(tokens.values()):
            raise RuntimeError("Synthetic login failed: the server is not using the disposable database.")
        employee, manager = tokens["employee"], tokens["manager"]
        check("S05", "Token identity resolves to the employee", "GET", "/api/me/", 200, token=employee,
              fields=lambda p: {"username": p.get("username"), "role": p.get("role"), "team": p.get("team")})
        check("S06", "Employee dashboard before submission", "GET", "/api/dashboard/", 200, token=employee,
              fields=lambda p: {"balance": p.get("balance"), "counts": p.get("counts")})
        _, created = check("S07", "Employee submits a leave request (W1)", "POST", "/api/requests/", 201, token=employee,
                           body={"leave_type": "vacation", "start_date": "2027-03-01", "end_date": "2027-03-05", "note": "PR1 smoke"},
                           fields=lambda p: {"id": p.get("id"), "status": p.get("status"), "employee.username": p.get("employee", {}).get("username"),
                                             "business_days": p.get("business_days")})
        k = created.get("id")
        check("S08", "Invalid submission (end before start) is rejected", "POST", "/api/requests/", 400, token=employee,
              body={"leave_type": "vacation", "start_date": "2027-04-09", "end_date": "2027-04-05"},
              fields=lambda p: {"error_keys": sorted(p.keys()) if isinstance(p, dict) else None})
        check("S09", "Employee cannot decide a request", "POST", f"/api/requests/{k}/decision/", 403, token=employee,
              body={"status": "approved"}, fields=lambda p: {"detail": p.get("detail")})
        check("S10", "Manager sees the same request k in the team list", "GET", "/api/requests/", 200, token=manager,
              fields=lambda p: {"contains_k": any(item.get("id") == k for item in p)})
        check("S11", "Manager approves the same persisted request k (W2)", "POST", f"/api/requests/{k}/decision/", 200, token=manager,
              body={"status": "approved"}, fields=lambda p: {"id": p.get("id"), "same_request": p.get("id") == k, "status": p.get("status")})
        check("S12", "Repeated decision on k is refused", "POST", f"/api/requests/{k}/decision/", 409, token=manager,
              body={"status": "rejected"}, fields=lambda p: {"detail": p.get("detail")})
        check("S13", "Employee dashboard after approval", "GET", "/api/dashboard/", 200, token=employee,
              fields=lambda p: {"balance": p.get("balance"), "counts": p.get("counts")})
    finally:
        server.terminate()
        try:
            server.wait(timeout=10)
        except subprocess.TimeoutExpired:
            server.kill()
        log.close()
    readback = shell_json(recorder, "09c-api-db-readback", READBACK_CODE, {"SMOKE_REQUEST_ID": str(k)})
    db_checks = {
        "same_request_id": readback["id"] == k,
        "owner_is_employee": readback["employee"] == "smoke-employee",
        "status_approved": readback["status"] == "approved",
        "decided_by_manager": readback["decided_by"] == "smoke-manager",
        "decided_at_set": readback["decided_at_set"],
        "one_request_only": readback["request_count"] == 1,
        "available_reduced_by_5": readback["balance"] == {"allowance": 10, "used": 5, "available": 5},
    }
    result = {"fixture": fixture, "http_checks": checks, "db_readback": readback, "db_checks": db_checks,
              "credentials": "random per run, never written; tokens shown as <redacted>",
              "pass": all(c["pass"] for c in checks) and all(db_checks.values())}
    (evidence / "09-api-smoke.json").write_text(json.dumps(result, indent=2) + "\n")
    return result


def frontend_build(recorder, run_dir):
    copy = run_dir / "frontend"
    shutil.copytree(ROOT / "frontend", copy, ignore=shutil.ignore_patterns("node_modules", "dist", "*.tsbuildinfo"))
    os.symlink(ROOT / "frontend" / "node_modules", copy / "node_modules")
    return recorder.run("10-frontend-build", ["npm", "run", "build"], cwd=copy,
                        note="Run in a temporary copy of frontend/ (node_modules symlinked) so the repository tree is not written.")


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--evidence-dir", type=Path, required=True)
    parser.add_argument("--port", type=int, default=8797)
    parser.add_argument("--skip-frontend", action="store_true")
    args = parser.parse_args(argv)
    evidence = args.evidence_dir.resolve()
    evidence.mkdir(parents=True, exist_ok=False)
    before = dev_db_metadata()
    shown = evidence.relative_to(ROOT) if evidence.is_relative_to(ROOT) else evidence
    summary = {"started_at_utc": utc(), "evidence_dir": str(shown), "development_database_before": before}
    run_dir = Path(tempfile.mkdtemp(prefix="leaveflow-baseline-repro-")).resolve()
    recorder = Recorder(evidence, run_dir)
    try:
        environment(evidence)
        database = write_settings(run_dir)
        guard_code = ("import django; django.setup(); from django.db import connection; from django.conf import settings; "
                      "print(connection.settings_dict['NAME']); print('REDIS_URL=' + repr(settings.REDIS_URL))")
        code, output = recorder.run("02-settings-guard", [sys.executable, "-c", guard_code])
        resolved = output.splitlines()[0].strip() if output else ""
        if code != 0 or Path(resolved).resolve() != database or Path(resolved).resolve() == DEV_DB.resolve():
            raise RuntimeError("Settings guard failed: Django did not resolve to the disposable database.")
        summary["disposable_database"] = str(database)
        recorder.run("03-django-check", [sys.executable, "manage.py", "check"])
        recorder.run("04-showmigrations-before", [sys.executable, "manage.py", "showmigrations"])
        recorder.run("05-migrate", [sys.executable, "manage.py", "migrate", "--no-input"])
        recorder.run("06-showmigrations-after", [sys.executable, "manage.py", "showmigrations"])
        recorder.run("07-migrate-check", [sys.executable, "manage.py", "migrate", "--check"])
        code, output = recorder.run("08-upstream-tests", [sys.executable, "manage.py", "test", "leave", "-v", "2"])
        found = re.search(r"Found (\d+) test", output)
        ran = re.search(r"Ran (\d+) tests? in", output)
        summary["upstream_tests"] = {"exit_code": code, "found": int(found.group(1)) if found else None,
                                     "ran": int(ran.group(1)) if ran else None,
                                     "ok": bool(re.search(r"^OK\s*$", output, re.MULTILINE)),
                                     "test_database": "in-memory" if "memorydb" in output else "see log"}
        summary["api_smoke_pass"] = api_smoke(recorder, evidence, args.port)["pass"]
        if not args.skip_frontend:
            frontend_build(recorder, run_dir)
    except Exception as exc:  # recorded, then the run fails
        summary["harness_error"] = f"{type(exc).__name__}: {exc}"
    finally:
        after = dev_db_metadata()
        summary.update(steps=recorder.steps, development_database_after=after,
                       development_database_unchanged=before == after, finished_at_utc=utc())
        shutil.rmtree(run_dir, ignore_errors=True)
        ok = (not summary.get("harness_error") and summary["development_database_unchanged"]
              and all(step["exit_code"] == 0 for step in recorder.steps) and summary.get("api_smoke_pass") is True)
        summary["overall_pass"] = ok
        (evidence / "summary.json").write_text(json.dumps(summary, indent=2) + "\n")
    print(json.dumps({k: summary.get(k) for k in ("steps", "upstream_tests", "api_smoke_pass", "development_database_unchanged", "overall_pass", "harness_error")}, indent=2))
    return 0 if summary["overall_pass"] else 1


if __name__ == "__main__":
    raise SystemExit(main())
